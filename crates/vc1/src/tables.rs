//! 不是某个实现的私有数据。生成器只做「读出来 + 排版」，不做任何推导。
//!
//! ## 为什么枚举也在里面
//!
//! 表里有几处是**符号名**而不是数字（`ff_vc1_ttfrm_to_tt = { TT_8X8, TT_8X4, … }`、
//! `ff_vc1_mv_pmode_table = { MV_PMODE_* }`）。生成器把枚举从源文件读出来翻译，
