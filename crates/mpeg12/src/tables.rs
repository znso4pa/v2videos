//! MPEG-1 的 DCT 系数 VLC 表（run/level → 码字）。
//!
//! **这张表不是手写的**：它由脚本从一份已知正确的实现里机械抽取，
//! 抽取后立刻做了「前缀无关 + Kraft 和 = 1」自检（见 `tests`）。
//! 手抄这种表最容易出的错是「整体对、个别条目错」，而这种错只会表现为
//! 画面局部花掉，反推代价极高 —— 所以宁可不写，也不凭记忆写。

/// 一条 run/level 码字。`bits` 位码 `code`（不含符号位）。
