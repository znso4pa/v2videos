//! 像素域算子：缩放 / 色彩空间转换 / 去隔行。
//!
//! ## 为什么独立 crate
//!
//! 这些算子与**编解码器无关**：谁解的码、谁要编，进来的都是 YUV420P 的 [`Frame`]。
//! 放进任何一个编解码器 crate 都会让另外几个反向依赖它；放进 `v2v-kernel` 又不对 ——
//! kernel 的判据是「把任意一个编解码器整个删掉，里面不该有函数变成死代码」，
//! 而缩放 / CSC 在「只做转码、不做滤镜」的构建里确实可以是死代码。
//!
//! ## 不进 C ABI
//!
//! `v2v-capi` 的头文件明确写着「不做 CSC / 缩放」—— 那是留给宿主的边界（宿主有
//! 自己的显示层，我们替它选缩放算法只会打架）。所以本 crate 只给 CLI 与未来的
//! 滤镜链用。
//!
//! ## 确定性
//!
//! **全部整数运算**，没有浮点、没有迭代到收敛、没有线程。坐标用 1/256 像素的定点，
//! 权重表按 `frac` 索引现算（不是运行时浮点表）。同输入 + 同参数 → **字节相同**，
//! 这是 B3「确定性契约」在像素域这一侧的底子。
//!
//! ## 边界约定（写死，别在别处另立一套）
//!
//! - **像素中心对齐**：目标像素 `d` 的采样位置是 `(d + 0.5) * src / dst - 0.5`，
//!   也就是「像素中心对像素中心」。这条口径决定了 1:1 缩放必须**逐字节相同**、
//!   2× 放大必须**精确命中原像素**（`d = 2i` 时采样位置正好是 `i`）。
//! - **边缘复制**（clamp），不补黑边：补黑会让画面边缘变暗，而 clamp 是
//!   ffmpeg / swscale 的默认，对账时不用额外解释差异。
//! - **4:2:0**：色度平面按 `ceil(w/2) × ceil(h/2)` 算，缩放目标同样向上取整。
#![deny(unsafe_code)]

pub mod csc;
pub mod deint;
pub mod scale;

pub use csc::{
    nv12_to_yuv420p, rgb24_to_yuv420p, rgb24_to_yuv444, yuv420p_to_nv12, yuv420p_to_rgb24,
    yuv444_to_rgb24,
};
pub use deint::{bob, weave, Field};
pub use scale::{resize, Algo};
